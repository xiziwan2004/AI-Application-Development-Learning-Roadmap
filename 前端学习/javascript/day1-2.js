// 1.2 模板字符串与解构
// ============================================================

// 准备数据
const user = { name: 'Ada', age: 30, city: 'London' };
const user1 = { name: '张三', age: 20, gender: '男' };

// 基本插值
console.log(`姓名:${user1.name},年龄:${user1.age},性别:${user1.gender}`);
// 输出：姓名:张三,年龄:20,性别:男


// ============================================================
// 1. 模板字符串
// ============================================================
// 反引号 ` 包裹的内容是模板字符串，与 ''/"" 一样表示字符串，
// 但额外支持：插值、多行、标签模板、嵌套。

// ---------- 1.1 插值：${} ----------
// 普通引号只能拼接，模板字符串可以直接在 ${} 中写表达式。
const a = 1;
const b = 2;

console.log(`a+b=${a + b}`);              // a+b=3
console.log(a + "+" + b + "=" + (a + b)); // 1+2=3（拼接写法，更繁琐）

// ---------- 1.2 多行字符串 ----------
// 模板字符串直接换行即可，普通引号需要写 \n 或拼接。
const html = `
  <div>
    <span>Hello</span>
  </div>
`;
console.log(html);
// 输出多行 HTML

const html1 = '<div>\n  <span>Hello</span>\n</div>';
console.log(html1);
// 输出相同内容，但写法更繁琐

// ---------- 1.3 标签模板 ----------
// 在模板字符串前写函数名，函数会收到「静态片段数组」和「插值列表」。
// 用途：区分哪些是写死的静态文本，哪些是动态插入的值。
function tag(strings, ...values) {
  console.log(strings); // [ '你好，', '，你今年 ', ' 岁' ]
  console.log(values);  // [ 'Ada', 30 ]
}

const name = "Ada";
const age = 30;
tag`你好，${name}，你今年 ${age} 岁`;

// ---------- 1.4 嵌套模板 ----------
// ${} 内可以再写模板字符串，常用于 map 生成 HTML 片段。
const items = ['苹果', '香蕉', '橘子'];
console.log(`我喜欢吃${items.map(i => `${i}`).join(',')}`);
// 输出：我喜欢吃苹果,香蕉,橘子


// ============================================================
// 2. 对象解构
// ============================================================
// 按属性名取值，支持默认值、重命名、剩余属性。

// ---------- 2.1 基本解构 + 默认值 + 重命名 ----------
const {
  name: userName,      // 重命名：user.name -> userName
  age: userAge,        // 重命名：user.age  -> userAge
  city = '未知',        // 默认值：只在 city 为 undefined 时生效
  name: nickname       // 再次重命名：user.name -> nickname
} = user;

console.log(userName, userAge, city, nickname);
// 输出：Ada 30 London Ada

// 说明：
// - name 被重命名为 userName 和 nickname，原变量名 name 不会被声明。
// - 默认值只对 undefined 生效，null 不会触发默认值。

// ---------- 2.2 剩余属性 ----------
// 把 city 单独取出，其余属性收集到 rest 新对象中。
const { city: _city, ...rest } = user;
console.log(rest); // { name: 'Ada', age: 30 }

// 说明：
// - _city 是重命名后的变量，下划线表示“占位、不关心”。
// - rest 是浅拷贝的新对象，修改它不影响原对象。


// ============================================================
// 3. 数组解构
// ============================================================
// 按位置取值，支持默认值、跳过元素、剩余元素。

// ---------- 3.1 基本解构 + 默认值 + 剩余元素 ----------
const [first, second = 100, ...others] = [1, 2, 3, 4];
console.log(first, second, others); // 1 2 [ 3, 4 ]
// second 对应位置是 2，不是 undefined，默认值 100 不生效。

const [first1, second1 = 100, ...others1] = [1, undefined, 4, 5];
console.log(first1, second1, others1); // 1 100 [ 4, 5 ]
// second1 对应位置是 undefined，默认值 100 生效。
// undefined 已被 second1 消费，不会进入 others1。

// 说明：
// - 默认值只在对应位置为 undefined（或位置不存在）时生效。
// - null、0、false、'' 都不会触发默认值。


// ============================================================
// 4. 交换变量
// ============================================================
// 右侧先求值生成新数组，再按位置解构赋值给左侧，避免互相覆盖。
let x = 1, y = 2;
[x, y] = [y, x];
console.log(x, y); // 2 1

// 说明：
// - 等价于先构造 [2, 1]，再赋值 x = 2、y = 1。
// - 语句开头用 [ 时，上一行要加分号，避免被解析为上一行的延续。